use std::io::Cursor;

use pure_vorbis::{BitReader, Decoder};

const FSB5_MAGIC: &[u8; 4] = b"FSB5";
const FSB5_MODE_VORBIS: u32 = 15;
const VORBIS_CHUNK_TYPE: u8 = 11;

pub struct AudioExport {
  pub bytes: Vec<u8>,
  pub extension: &'static str,
  pub details: String,
}

#[derive(Debug, Clone)]
pub struct AudioClipMeta {
  pub name: String,
  pub channels: u32,
  pub frequency: u32,
  pub bits_per_sample: u32,
  pub length_seconds: f32,
  pub source: String,
  pub offset: u64,
  pub size: u64,
  pub compression_format: i32,
}

#[derive(Debug, Clone)]
struct Fsb5Header {
  version: u32,
  num_samples: u32,
  sample_headers_size: u32,
  name_table_size: u32,
  data_size: u32,
  mode: u32,
}

#[derive(Debug, Clone)]
struct Fsb5Sample {
  frequency: u32,
  channels: u32,
  data_offset: usize,
  samples: u32,
  vorbis_crc32: u32,
  payload: Vec<u8>,
}

pub fn export_audio_clip(resource_name: &str, resource_data: &[u8], meta: &AudioClipMeta) -> Result<AudioExport, String> {
  let (header, sample) = parse_fsb5(resource_data)?;
  if header.num_samples != 1 {
    return Err(format!("暂不支持多样本 FSB5: {}", resource_name));
  }
  if header.mode != FSB5_MODE_VORBIS {
    return Err(format!("暂不支持该 AudioClip 编码模式: {}", header.mode));
  }
  let pcm = decode_vorbis_to_pcm16(&sample)?;
  let wav = encode_wav_pcm16(meta.channels, meta.frequency, &pcm)?;
  Ok(AudioExport {
    bytes: wav,
    extension: "wav",
    details: format!(
      "audio_channels: {}\naudio_frequency: {}\naudio_bits_per_sample: {}\naudio_duration_seconds: {:.3}\naudio_compression: {}\naudio_sample_count: {}\naudio_payload_size: {}",
      meta.channels,
      meta.frequency,
      meta.bits_per_sample,
      meta.length_seconds,
      compression_format_name(meta.compression_format),
      sample.samples,
      resource_data.len()
    ),
  })
}

fn parse_fsb5(data: &[u8]) -> Result<(Fsb5Header, Fsb5Sample), String> {
  if data.len() < 64 {
    return Err("FSB5 数据过短".to_string());
  }
  if &data[..4] != FSB5_MAGIC {
    return Err("AudioClip 资源不是 FSB5".to_string());
  }
  let header = Fsb5Header {
    version: read_u32_le(data, 4)?,
    num_samples: read_u32_le(data, 8)?,
    sample_headers_size: read_u32_le(data, 12)?,
    name_table_size: read_u32_le(data, 16)?,
    data_size: read_u32_le(data, 20)?,
    mode: read_u32_le(data, 24)?,
  };
  let sample_header_start = fsb5_header_size(header.version);
  let sample_header_end = sample_header_start + header.sample_headers_size as usize;
  if sample_header_end > data.len() {
    return Err("FSB5 sample header 越界".to_string());
  }
  let sample_blob = &data[sample_header_start..sample_header_end];
  let raw = read_u64_le(sample_blob, 0)?;
  let mut cursor = 8usize;
  let mut next_chunk = bit_slice_u64(raw, 0, 1) != 0;
  let mut frequency_code = bit_slice_u64(raw, 1, 4) as u32;
  let channels = bit_slice_u64(raw, 5, 1) as u32 + 1;
  let data_offset = (bit_slice_u64(raw, 6, 28) as usize) * 16;
  let samples = bit_slice_u64(raw, 34, 30) as u32;
  let mut vorbis_crc32 = None;

  while next_chunk {
    if cursor + 4 > sample_blob.len() {
      return Err("FSB5 metadata chunk 越界".to_string());
    }
    let chunk_header = read_u32_le(sample_blob, cursor)?;
    cursor += 4;
    next_chunk = (chunk_header & 0x1) != 0;
    let chunk_size = ((chunk_header >> 1) & 0x00ff_ffff) as usize;
    let chunk_type = ((chunk_header >> 25) & 0x7f) as u8;
    if cursor + chunk_size > sample_blob.len() {
      return Err("FSB5 metadata payload 越界".to_string());
    }
    let chunk_payload = &sample_blob[cursor..cursor + chunk_size];
    cursor += chunk_size;
    match chunk_type {
      2 if chunk_payload.len() >= 4 => {
        frequency_code = read_u32_le(chunk_payload, 0)?;
      }
      VORBIS_CHUNK_TYPE if chunk_payload.len() >= 4 => {
        vorbis_crc32 = Some(read_u32_le(chunk_payload, 0)?);
      }
      _ => {}
    }
  }

  let data_start = sample_header_start + header.sample_headers_size as usize + header.name_table_size as usize + data_offset;
  let data_end = sample_header_start + header.sample_headers_size as usize + header.name_table_size as usize + header.data_size as usize;
  if data_start > data_end || data_end > data.len() {
    return Err("FSB5 音频数据范围非法".to_string());
  }
  let payload = data[data_start..data_end].to_vec();
  Ok((
    header,
    Fsb5Sample {
      frequency: fsb5_frequency(frequency_code).ok_or_else(|| format!("未知 FSB5 频率编码: {frequency_code}"))?,
      channels,
      data_offset,
      samples,
      vorbis_crc32: vorbis_crc32.ok_or_else(|| "FSB5 Vorbis 缺少 setup header CRC".to_string())?,
      payload,
    },
  ))
}

fn decode_vorbis_to_pcm16(sample: &Fsb5Sample) -> Result<Vec<i16>, String> {
  let mut builder = Decoder::builder();
  let ident = build_vorbis_ident_packet(sample.channels as u8, sample.frequency);
  let comment = build_vorbis_comment_packet();
  let setup = vorbis_setup_packet(sample.vorbis_crc32)?;
  builder
    .read_ident_packet(&mut BitReader::new(Cursor::new(ident)))
    .map_err(|err| format!("Vorbis ident 解析失败: {err:?}"))?;
  builder
    .read_comment_packet(&mut BitReader::new(Cursor::new(comment)))
    .map_err(|err| format!("Vorbis comment 解析失败: {err:?}"))?;
  builder
    .read_setup_packet(&mut BitReader::new(Cursor::new(setup)))
    .map_err(|err| format!("Vorbis setup 解析失败: {err:?}"))?;
  let mut decoder = builder.build();

  let mut pcm = Vec::new();
  let mut offset = 0usize;
  while offset + 2 <= sample.payload.len() {
    let packet_len = u16::from_le_bytes([sample.payload[offset], sample.payload[offset + 1]]) as usize;
    offset += 2;
    if packet_len == 0 {
      break;
    }
    if offset + packet_len > sample.payload.len() {
      return Err("Vorbis packet 超出样本范围".to_string());
    }
    let packet = &sample.payload[offset..offset + packet_len];
    offset += packet_len;
    decoder
      .decode(&mut BitReader::new(Cursor::new(packet)))
      .map_err(|err| format!("Vorbis 音频包解码失败: {err:?}"))?;
    if decoder.samples().is_empty() {
      continue;
    }
    pcm.extend(decoder.samples().interleave().map(float_to_pcm16));
  }
  if pcm.is_empty() {
    return Err("未解出有效 PCM 数据".to_string());
  }
  Ok(pcm)
}

fn build_vorbis_ident_packet(channels: u8, frequency: u32) -> Vec<u8> {
  let mut packet = Vec::with_capacity(30);
  packet.push(0x01);
  packet.extend_from_slice(b"vorbis");
  packet.extend_from_slice(&0u32.to_le_bytes());
  packet.push(channels);
  packet.extend_from_slice(&frequency.to_le_bytes());
  packet.extend_from_slice(&0u32.to_le_bytes());
  packet.extend_from_slice(&0u32.to_le_bytes());
  packet.extend_from_slice(&0u32.to_le_bytes());
  packet.push((11 << 4) | 8);
  packet.push(1);
  packet
}

fn build_vorbis_comment_packet() -> Vec<u8> {
  let vendor = b"apkworkshop";
  let mut packet = Vec::with_capacity(64);
  packet.push(0x03);
  packet.extend_from_slice(b"vorbis");
  packet.extend_from_slice(&(vendor.len() as u32).to_le_bytes());
  packet.extend_from_slice(vendor);
  packet.extend_from_slice(&0u32.to_le_bytes());
  packet.push(1);
  packet
}

fn vorbis_setup_packet(crc32: u32) -> Result<Vec<u8>, String> {
  match crc32 {
    0xd6e0bbd4 => Ok(VORBIS_HEADER_0XD6E0BBD4.to_vec()),
    _ => Err(format!("未内置该 AudioClip 的 Vorbis setup header: 0x{crc32:08x}")),
  }
}

fn encode_wav_pcm16(channels: u32, sample_rate: u32, samples: &[i16]) -> Result<Vec<u8>, String> {
  if channels == 0 {
    return Err("WAV 声道数非法".to_string());
  }
  let byte_rate = sample_rate
    .checked_mul(channels)
    .and_then(|value| value.checked_mul(2))
    .ok_or_else(|| "WAV byte rate 溢出".to_string())?;
  let block_align = channels
    .checked_mul(2)
    .ok_or_else(|| "WAV block align 溢出".to_string())? as u16;
  let data_len = samples
    .len()
    .checked_mul(2)
    .ok_or_else(|| "WAV 数据长度溢出".to_string())?;
  let riff_len = 36usize
    .checked_add(data_len)
    .ok_or_else(|| "WAV RIFF 长度溢出".to_string())?;

  let mut wav = Vec::with_capacity(riff_len + 8);
  wav.extend_from_slice(b"RIFF");
  wav.extend_from_slice(&(riff_len as u32).to_le_bytes());
  wav.extend_from_slice(b"WAVE");
  wav.extend_from_slice(b"fmt ");
  wav.extend_from_slice(&16u32.to_le_bytes());
  wav.extend_from_slice(&1u16.to_le_bytes());
  wav.extend_from_slice(&(channels as u16).to_le_bytes());
  wav.extend_from_slice(&sample_rate.to_le_bytes());
  wav.extend_from_slice(&byte_rate.to_le_bytes());
  wav.extend_from_slice(&block_align.to_le_bytes());
  wav.extend_from_slice(&16u16.to_le_bytes());
  wav.extend_from_slice(b"data");
  wav.extend_from_slice(&(data_len as u32).to_le_bytes());
  for sample in samples {
    wav.extend_from_slice(&sample.to_le_bytes());
  }
  Ok(wav)
}

fn float_to_pcm16(value: f32) -> i16 {
  let clamped = value.clamp(-1.0, 1.0);
  let scaled = (clamped * 32767.0).round();
  if scaled > i16::MAX as f32 {
    i16::MAX
  } else if scaled < i16::MIN as f32 {
    i16::MIN
  } else {
    scaled as i16
  }
}

fn compression_format_name(value: i32) -> &'static str {
  match value {
    0 => "PCM",
    1 => "Vorbis",
    2 => "ADPCM",
    3 => "MP3",
    4 => "PSMVAG",
    5 => "HEVAG",
    6 => "XMA",
    7 => "AAC",
    8 => "GCADPCM",
    9 => "ATRAC9",
    _ => "Unknown",
  }
}

fn fsb5_header_size(version: u32) -> usize {
  if version == 0 {
    64
  } else {
    60
  }
}

fn fsb5_frequency(code: u32) -> Option<u32> {
  match code {
    1 => Some(8000),
    2 => Some(11000),
    3 => Some(11025),
    4 => Some(16000),
    5 => Some(22050),
    6 => Some(24000),
    7 => Some(32000),
    8 => Some(44100),
    9 => Some(48000),
    other if other > 1000 => Some(other),
    _ => None,
  }
}

fn bit_slice_u64(value: u64, start: usize, len: usize) -> u64 {
  if len == 0 {
    return 0;
  }
  let mask = (1u64 << len) - 1;
  (value >> start) & mask
}

fn read_u32_le(data: &[u8], offset: usize) -> Result<u32, String> {
  let bytes = data
    .get(offset..offset + 4)
    .ok_or_else(|| "读取 u32 时越界".to_string())?;
  Ok(u32::from_le_bytes(bytes.try_into().unwrap_or([0; 4])))
}

fn read_u64_le(data: &[u8], offset: usize) -> Result<u64, String> {
  let bytes = data
    .get(offset..offset + 8)
    .ok_or_else(|| "读取 u64 时越界".to_string())?;
  Ok(u64::from_le_bytes(bytes.try_into().unwrap_or([0; 8])))
}

